import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { PY_VOICE_LABEL, codePointCompare, pyClock, pyFirstInt, pyFixed, pyRound, pyRoundInt, pySum } from './speaker-shadow-numeric.js'

// Vectors written by CPython 3.15 (`python3 -I __fixtures__/speaker-shadow/cpython_numeric_vectors.py`),
// floats as float.hex() so nothing is lost in transit. Synthetic numbers only.
const vectors = JSON.parse(readFileSync(join(import.meta.dirname, '__fixtures__', 'speaker-shadow', 'cpython-numeric-vectors.json'), 'utf8'))

function fromHex(text: string): number {
  const m = /^(-?)0x([01])\.([0-9a-f]*)p([+-]\d+)$/.exec(text)
  if (!m) throw new Error(`bad hex float ${text}`)
  const mantissa = BigInt(`0x${m[2]}${m[3] || '0'}`)
  const value = Number(mantissa) * 2 ** (Number(m[4]) - 4 * (m[3] || '0').length)
  return m[1] ? -value : value
}

describe('Python-compatible numerics (CPython 3.15 vectors)', () => {
  it('was generated by CPython 3.12 or later, where sum() is compensated', () => {
    const [major, minor] = String(vectors.python).split('.').map(Number)
    expect(major * 100 + minor).toBeGreaterThanOrEqual(312)
  })

  it('sum() matches bit for bit, including cancellation-heavy inputs', () => {
    expect(vectors.sum.length).toBeGreaterThan(50)
    for (const row of vectors.sum) expect(Object.is(pySum(row.xs.map(fromHex)), fromHex(row.sum))).toBe(true)
  })

  it('a plain left-to-right loop would NOT match (the compensation is load-bearing)', () => {
    const misses = vectors.sum.filter((row: { xs: string[]; sum: string }) => {
      let plain = 0
      for (const x of row.xs.map(fromHex)) plain += x
      return !Object.is(plain, fromHex(row.sum))
    })
    expect(misses.length).toBeGreaterThan(10)
  })

  it('round(x, n) rounds half to even on the exact binary value', () => {
    for (const row of vectors.round) expect(Object.is(pyRound(fromHex(row.x), row.nd), fromHex(row.r))).toBe(true)
    expect(pyRound(0.125, 2)).toBe(0.12)
    expect(pyRound(0.375, 2)).toBe(0.38)
  })

  it("'%.nf' % x matches, including exact ties that toFixed rounds up", () => {
    for (const row of vectors.fixed) expect(pyFixed(fromHex(row.x), row.nd)).toBe(row.s)
    expect(pyFixed(0.125, 2)).toBe('0.12')
    expect((0.125).toFixed(2)).toBe('0.13')
    expect(pyFixed(-0, 2)).toBe('-0.00')
    expect(pyFixed(15, 0)).toBe('15')
  })

  it('round(x) is an int, half to even', () => {
    for (const row of vectors.roundInt) expect(pyRoundInt(fromHex(row.x))).toBe(row.r)
    expect([pyRoundInt(0.5), pyRoundInt(1.5), pyRoundInt(2.5), pyRoundInt(-0.5)]).toEqual([0, 2, 2, 0])
  })

  it('the Voice pattern and its number use Unicode \\s and \\d like Python', () => {
    for (const row of vectors.voice) expect(PY_VOICE_LABEL.test(row.s)).toBe(row.m)
    for (const row of vectors.firstInt) expect(pyFirstInt(row.s)).toBe(row.v)
  })

  it('orders strings by code point', () => {
    expect(['S2', 'S10', 'S1'].sort(codePointCompare)).toEqual(['S1', 'S10', 'S2'])
    // UTF-16 order puts the surrogate pair first; code point order puts it last.
    expect(['\u{1F600}', 'ｚ'].sort(codePointCompare)).toEqual(['ｚ', '\u{1F600}'])
    expect(codePointCompare('ab', 'a')).toBe(1)
    expect(codePointCompare('a', 'a')).toBe(0)
  })

  it('formats a call clock like the report', () => {
    expect(pyClock(59.5)).toBe('1:00')
    expect(pyClock(60.5)).toBe('1:00')
    expect(pyClock(3725.2)).toBe('1:02:05')
  })
})
